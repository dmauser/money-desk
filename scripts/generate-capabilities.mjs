#!/usr/bin/env node
// Generate docs/CAPABILITIES.md from the SPECIALISTS table in registry.mjs.
// Single source of truth — never edit docs/CAPABILITIES.md by hand.
//
// Usage:
//   node scripts/generate-capabilities.mjs           # write the file
//   node scripts/generate-capabilities.mjs --check   # exit 1 if drift; print diff
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { SPECIALISTS, specialistCount } from "../extensions/money-desk/registry.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const OUT = join(REPO, "docs", "CAPABILITIES.md");
const CHECK_MODE = process.argv.includes("--check");

const escape = (s) => s.replace(/\|/g, "\\|");

function render() {
    const lines = [];
    lines.push("<!-- AUTO-GENERATED by scripts/generate-capabilities.mjs — do not edit by hand. -->");
    lines.push("<!-- Run: npm run docs:capabilities -->");
    lines.push("");
    lines.push("# Money Desk Capabilities");
    lines.push("");
    lines.push(`Money Desk ships **${specialistCount} specialists** with **${countSkills()} skills** plus 2 discovery tools (\`md_capabilities\`, \`md_route\`) — a total of **${countTools()} tools** registered with Copilot CLI.`);
    lines.push("");
    lines.push("## Specialists");
    lines.push("");
    lines.push("| # | Domain | Prefix | Role tool | Orchestrator | Trigger phrases (example) |");
    lines.push("|---|--------|--------|-----------|--------------|---------------------------|");
    SPECIALISTS.forEach((s, i) => {
        const triggers = sampleTriggers(s.route);
        lines.push(`| ${i + 1} | ${s.icon} ${escape(s.domain)} | \`${s.prefix}\` | \`${s.prefix}_role\` | \`${s.prefix}_orchestrate\` | ${triggers} |`);
    });
    lines.push("");
    lines.push("## Skills by specialist");
    lines.push("");
    for (const s of SPECIALISTS) {
        lines.push(`### ${s.icon} ${s.domain} (\`${s.prefix}\`)`);
        lines.push("");
        lines.push("| Skill | Tool | What it does |");
        lines.push("|-------|------|--------------|");
        for (const sk of s.skills) {
            const desc = sk.description
                .replace(/^\*\*[^*]+\*\* — /, "")
                .replace(/\|/g, "\\|");
            lines.push(`| **${escape(sk.displayName)}** | \`${s.prefix}_skill_${sk.id}\` | ${desc} |`);
        }
        lines.push("");
    }
    lines.push("## Discovery tools");
    lines.push("");
    lines.push("| Tool | What it does |");
    lines.push("|------|--------------|");
    lines.push("| `md_capabilities` | Returns the team map (this content, condensed). Call first when the user mentions money-desk or any personal-finance topic. |");
    lines.push("| `md_route` | Given a free-text query, returns which specialist(s) handle it. Takes `{ query }`. |");
    lines.push("");
    return lines.join("\n") + "\n";
}

function countSkills() {
    return SPECIALISTS.reduce((n, s) => n + s.skills.length, 0);
}

function countTools() {
    return SPECIALISTS.reduce((n, s) => n + 2 + s.skills.length, 0) + 2;
}

function sampleTriggers(re) {
    const src = re.source;
    const words = [...src.matchAll(/[a-zA-Z][a-zA-Z0-9_]{3,}/g)]
        .map((m) => m[0])
        .filter((w) => !["true", "false", "null", "undefined"].includes(w))
        .slice(0, 4);
    return words.length ? words.map((w) => `\`${w}\``).join(", ") : "—";
}

const content = render();

if (CHECK_MODE) {
    let existing = "";
    try { existing = await readFile(OUT, "utf8"); } catch { /* missing */ }
    if (existing !== content) {
        process.stderr.write(`docs/CAPABILITIES.md is out of date.\nRun: npm run docs:capabilities\n`);
        process.exit(1);
    }
    process.stdout.write("docs/CAPABILITIES.md is up to date.\n");
} else {
    await writeFile(OUT, content, "utf8");
    process.stdout.write(`Wrote ${OUT}\n`);
}
