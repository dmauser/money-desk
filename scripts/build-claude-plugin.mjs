#!/usr/bin/env node
// Builds the Claude plugin at plugins/money-desk/ from the canonical sources.
//
// Why a subfolder: claude.ai's marketplace sync (used by Claude Desktop's
// Customize → Plugins) rejects plugins whose marketplace source is the repo
// root ("source": "./") even though Claude Code's CLI accepts them
// (anthropics/claude-code#106574, #91933). Every official marketplace keeps
// each plugin in its own folder, so we do too.
//
// Canonical sources (edit these, never the generated copy):
//   extensions/money-desk/           → plugins/money-desk/runtime/   (minus tests/)
//   claude-plugin/plugin.json        → plugins/money-desk/.claude-plugin/plugin.json (version from package.json)
//   claude-plugin/skills/            → plugins/money-desk/skills/
//
// Usage: node scripts/build-claude-plugin.mjs [--check]
//   --check  exit 1 if the generated plugin is out of date (used by tests).

import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(REPO, "plugins", "money-desk");
const pkg = JSON.parse(readFileSync(join(REPO, "package.json"), "utf8"));

const EXCLUDE = new Set(["tests", "__pycache__", ".pytest_cache", "node_modules", "extension.mjs"]);

function listFiles(dir, base = dir, out = []) {
    for (const name of readdirSync(dir).sort()) {
        if (EXCLUDE.has(name) || name.endsWith(".pyc")) continue;
        const p = join(dir, name);
        if (statSync(p).isDirectory()) listFiles(p, base, out);
        else out.push(relative(base, p));
    }
    return out;
}

// Build the expected file map: relative path in OUT -> Buffer contents.
function expected() {
    const files = new Map();
    const runtimeSrc = join(REPO, "extensions", "money-desk");
    for (const rel of listFiles(runtimeSrc)) files.set(join("runtime", rel), readFileSync(join(runtimeSrc, rel)));
    files.set(
        join("runtime", "package.json"),
        Buffer.from(JSON.stringify({ name: "money-desk-runtime", private: true, type: "module", version: pkg.version }, null, 2) + "\n"),
    );

    const manifest = JSON.parse(readFileSync(join(REPO, "claude-plugin", "plugin.json"), "utf8"));
    manifest.version = pkg.version;
    files.set(join(".claude-plugin", "plugin.json"), Buffer.from(JSON.stringify(manifest, null, 2) + "\n"));

    files.set(
        ".mcp.json",
        Buffer.from(
            JSON.stringify(
                { mcpServers: { "money-desk": { command: "node", args: ["${CLAUDE_PLUGIN_ROOT}/runtime/mcp-server.mjs"] } } },
                null,
                2,
            ) + "\n",
        ),
    );

    const skillsSrc = join(REPO, "claude-plugin", "skills");
    for (const rel of listFiles(skillsSrc)) files.set(join("skills", rel), readFileSync(join(skillsSrc, rel)));

    files.set(
        "README.md",
        Buffer.from(
            "# Money Desk — Claude plugin (generated)\n\n" +
                "This folder is generated by `npm run build:plugin` (`scripts/build-claude-plugin.mjs`) from\n" +
                "`extensions/money-desk/` and `claude-plugin/`. Do not edit it by hand; edit the sources and rebuild.\n\n" +
                "Install: `/plugin marketplace add dmauser/money-desk` then `/plugin install money-desk@money-desk`.\n",
        ),
    );
    return files;
}

const norm = (b) => b.toString("utf8").replace(/\r\n/g, "\n");

function diff(files) {
    const problems = [];
    const actual = existsSync(OUT) ? new Set(listFiles(OUT)) : new Set();
    for (const [rel, buf] of files) {
        const p = join(OUT, rel);
        if (!existsSync(p)) problems.push(`missing: ${rel}`);
        else if (norm(readFileSync(p)) !== norm(buf)) problems.push(`stale: ${rel}`);
        actual.delete(rel);
    }
    for (const rel of actual) problems.push(`extra: ${rel}`);
    return problems;
}

const files = expected();

if (process.argv.includes("--check")) {
    const problems = diff(files);
    if (problems.length) {
        console.error(`plugins/money-desk is out of date — run \`npm run build:plugin\`:\n  ${problems.join("\n  ")}`);
        process.exit(1);
    }
    console.log("plugins/money-desk is up to date.");
} else {
    rmSync(OUT, { recursive: true, force: true });
    for (const [rel, buf] of files) {
        const p = join(OUT, rel);
        mkdirSync(dirname(p), { recursive: true });
        writeFileSync(p, buf);
    }
    console.log(`Built plugins/money-desk (${files.size} files, v${pkg.version}).`);
}
